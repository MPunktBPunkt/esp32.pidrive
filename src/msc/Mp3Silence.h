/**
 * CBR MP3 silence filler for MSC station stubs (Baustelle B2).
 * Tiles a fixed 48 kbit/s MPEG-1 Layer III stereo frame so HU decoders
 * hold the track for the full slot size instead of skipping on 0xFF padding.
 */
